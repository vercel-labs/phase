import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { parse } from '@babel/parser';

const scriptsDirectory = dirname(fileURLToPath(import.meta.url));
const root = process.argv[2] ?? join(scriptsDirectory, '..');
const kebabCase = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

const entries = await readdir(root, { withFileTypes: true });
const slugGroups = await Promise.all(
  entries
    .filter((entry) => entry.isDirectory() && entry.name !== 'scripts')
    .map(discoverExamples),
);
const slugs = slugGroups.flat().toSorted();

async function discoverExamples(entry) {
  const directory = join(root, entry.name);
  const files = await readdir(directory, {
    withFileTypes: true,
  });
  const variants = files.filter(
    (file) => file.isFile() && file.name.endsWith('.tsx'),
  );
  const hasMeta = files.some(
    (file) => file.isFile() && file.name === 'meta.ts',
  );
  if (!hasMeta && variants.length === 0) return [];

  if (!kebabCase.test(entry.name)) {
    throw new Error(`example directory "${entry.name}" must be kebab-case`);
  }
  if (!hasMeta) {
    throw new Error(`${entry.name}/meta.ts is required`);
  }
  if (variants.length === 0) {
    throw new Error(`${entry.name} must contain at least one .tsx example`);
  }

  const metaModule = await import(
    pathToFileURL(join(directory, 'meta.ts')).href
  );
  if (!isValidMeta(metaModule.default)) {
    throw new Error(
      `${entry.name}/meta.ts must include a title, a description, and at least one export`,
    );
  }

  return Promise.all(
    variants.map(async (file) => {
      const variant = file.name.slice(0, -4);
      if (!kebabCase.test(variant)) {
        throw new Error(
          `${entry.name}/${file.name} must use a kebab-case file name`,
        );
      }
      const source = await readFile(join(directory, file.name), 'utf8');
      const { program } = parse(source, {
        sourceType: 'module',
        sourceFilename: file.name,
        plugins: ['typescript', 'jsx'],
        errorRecovery: true,
      });
      if (!hasClientDirective(program)) {
        throw new Error(
          `${entry.name}/${file.name} must start with 'use client'`,
        );
      }
      if (!hasDefaultExport(program)) {
        throw new Error(
          `${entry.name}/${file.name} must have a default export`,
        );
      }
      return `${entry.name}/${variant}`;
    }),
  );
}

const imports = slugs
  .map((slug) => `  '${slug}': () => import('./${slug}'),`)
  .join('\n');
const manifest = `// Generated by scripts/generate-manifest.mjs. Do not edit.
import type { ComponentType } from 'react';

export type ExampleModule = { default: ComponentType };
export type ExampleLoader = () => Promise<ExampleModule>;

export const manifest = {
${imports}
} satisfies Record<string, ExampleLoader>;

export type ExampleSlug = keyof typeof manifest;
`;

await writeFile(join(root, 'manifest.ts'), manifest);

process.stdout.write(
  `Generated ${relative(process.cwd(), join(root, 'manifest.ts'))}\n`,
);

// The parser keeps a file's leading string statements as directives, so the
// first one is the file's first statement.
function hasClientDirective(program) {
  return program.directives[0]?.value.value === 'use client';
}

// `export default <expression>` and `export default function/class/...`;
// `export =` and `export { name as default }` don't count.
function hasDefaultExport(program) {
  return program.body.some(
    (statement) => statement.type === 'ExportDefaultDeclaration',
  );
}

function isValidMeta(value) {
  if (!value || typeof value !== 'object') return false;
  if (typeof value.title !== 'string' || value.title.trim() === '')
    return false;
  if (
    typeof value.description !== 'string' ||
    value.description.trim() === ''
  ) {
    return false;
  }
  return (
    Array.isArray(value.exports) &&
    value.exports.length > 0 &&
    value.exports.every(
      (exportName) =>
        typeof exportName === 'string' && exportName.trim() !== '',
    )
  );
}
