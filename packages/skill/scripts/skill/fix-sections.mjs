import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

import { parseMarkdown } from './markdown.mjs';

const FIX_POINTER = /^references\/([\w./-]+\.md)#([\w-]+)$/;

export function parseFixPointer(pointer) {
  const match = FIX_POINTER.exec(pointer);
  if (!match || match[1].split('/').includes('..')) {
    throw new Error(
      `fix pointer is malformed or missing an anchor: ${pointer}`,
    );
  }
  return { file: match[1], anchor: match[2] };
}

export function extractFixSection(source, anchor) {
  if (/^ {0,3}(?:=+|-+)[ \t]*$/m.test(source)) {
    throw new Error(
      'setext headings and thematic breaks are unsupported in fix sections; use ATX headings',
    );
  }

  const { headings, lines } = parseMarkdown(source);
  const startIndex = headings.findIndex((heading) => heading.anchor === anchor);
  if (startIndex === -1) throw new Error(`fix anchor not found: #${anchor}`);

  const start = headings[startIndex];
  const next = headings
    .slice(startIndex + 1)
    .find((heading) => heading.level <= start.level);
  const end = next?.lineIndex ?? lines.length;
  const body = lines.slice(start.bodyLineIndex, end).join('\n').trim();
  if (body === '') throw new Error(`fix section is empty: #${anchor}`);

  return lines.slice(start.lineIndex, end).join('\n').trim();
}

export function collectFixSections(signals, refsDir) {
  const sections = new Map();

  for (const signal of signals) {
    if (sections.has(signal.fix)) continue;

    try {
      const { file, anchor } = parseFixPointer(signal.fix);
      const filePath = join(refsDir, file);
      if (!existsSync(filePath)) {
        throw new Error(`fix points to missing file: ${signal.fix}`);
      }
      const source = readFileSync(filePath, 'utf8');
      sections.set(signal.fix, extractFixSection(source, anchor));
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      throw new Error(`${signal.id}: ${message}`, { cause: error });
    }
  }

  return new Map(
    [...sections].toSorted(([left], [right]) => left.localeCompare(right)),
  );
}

export function renderFixSectionsModule(sections) {
  const values = Object.fromEntries(sections);
  return `// Generated by scripts/skill/generate-fix-sections.mjs. Do not edit.\n\nexport const FIX_SECTIONS: Readonly<Record<string, string>> = ${JSON.stringify(values, null, 2)};\n`;
}
